"""Exploratory data analysis: figures + a markdown summary.

Run:  python -m wdbc.eda

EDA answers "what does the data look like before we model it?":
  - Is the label balanced?          -> class_balance.png
  - Which features separate B / M?  -> feature_separation.png (effect sizes)
  - Are features redundant?         -> correlation_heatmap.png, list of |r| > 0.95 pairs
  - Any data-quality problems?      -> checks in data.validate()

It uses only the TRAINING split, so nothing seen here biases the final test.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from .config import load_config
from .data import CLASS_NAMES, FEATURE_NAMES, load_dataset, split
from .preprocessing import ZScoreScaler, correlation_from_z


def effect_sizes(X: pd.DataFrame, y: pd.Series) -> pd.Series:
    """Cohen's d per feature: (mean_M - mean_B) / pooled std.
    Bigger |d| = the feature separates the classes better on its own."""
    a, b = X[y == 1], X[y == 0]
    na, nb = len(a), len(b)
    pooled = np.sqrt(((na - 1) * a.var() + (nb - 1) * b.var()) / (na + nb - 2))
    return ((a.mean() - b.mean()) / pooled).sort_values(ascending=False)


def correlated_pairs(R: pd.DataFrame, cutoff: float = 0.95) -> pd.DataFrame:
    rows = []
    cols = R.columns
    for i in range(len(cols)):
        for j in range(i + 1, len(cols)):
            if abs(R.iloc[i, j]) >= cutoff:
                rows.append((cols[i], cols[j], R.iloc[i, j]))
    return pd.DataFrame(rows, columns=["feature_a", "feature_b", "r"]).sort_values(
        "r", ascending=False, key=abs
    )


def run_eda(cfg: dict) -> dict:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    figs = cfg["paths"]["figures_dir"]
    figs.mkdir(parents=True, exist_ok=True)
    X, y = load_dataset(cfg["data"]["raw_path"])
    X_tr, _, y_tr, _ = split(X, y, cfg["data"]["test_size"], cfg["data"]["random_state"])

    # 1. Class balance
    counts = y.map(CLASS_NAMES).value_counts()
    fig, ax = plt.subplots(figsize=(4.5, 3.5))
    ax.bar(counts.index, counts.values, color=["tab:blue", "tab:red"])
    for i, v in enumerate(counts.values):
        ax.text(i, v + 5, f"{v} ({v / len(y):.0%})", ha="center")
    ax.set(title="Class balance (all 569 samples)", ylabel="Samples")
    fig.tight_layout()
    fig.savefig(figs / "class_balance.png", dpi=150)
    plt.close(fig)

    # 2. Correlation matrix from z-scores, R = Z'Z/(n-1)  (MLA Lecture 8 idea)
    Z = ZScoreScaler().fit_transform(X_tr)
    R = pd.DataFrame(correlation_from_z(Z), index=FEATURE_NAMES, columns=FEATURE_NAMES)
    fig, ax = plt.subplots(figsize=(10, 8.5))
    im = ax.imshow(R.values, cmap="RdBu_r", vmin=-1, vmax=1)
    ax.set_xticks(range(30), FEATURE_NAMES, rotation=90, fontsize=7)
    ax.set_yticks(range(30), FEATURE_NAMES, fontsize=7)
    fig.colorbar(im, ax=ax, shrink=0.8, label="Pearson r")
    ax.set_title("Feature correlation matrix R = Z'Z/(n-1), training split")
    fig.tight_layout()
    fig.savefig(figs / "correlation_heatmap.png", dpi=150)
    plt.close(fig)

    # 3. Which features separate the classes
    d = effect_sizes(X_tr, y_tr)
    top = d.abs().sort_values(ascending=False).index[:6]
    fig, axes = plt.subplots(2, 3, figsize=(11, 6))
    for ax, feat in zip(axes.ravel(), top, strict=True):
        for label, color in [(0, "tab:blue"), (1, "tab:red")]:
            ax.hist(
                X_tr.loc[y_tr == label, feat],
                bins=25,
                alpha=0.55,
                color=color,
                label=CLASS_NAMES[label],
                density=True,
            )
        ax.set_title(f"{feat}  (d = {d[feat]:.2f})", fontsize=10)
        ax.legend(fontsize=8)
    fig.suptitle("Six most separating features (Cohen's d), training split")
    fig.tight_layout()
    fig.savefig(figs / "feature_separation.png", dpi=150)
    plt.close(fig)

    pairs = correlated_pairs(R)
    summary = {
        "n_samples": len(y),
        "n_features": int(X.shape[1]),
        "n_benign": int((y == 0).sum()),
        "n_malignant": int((y == 1).sum()),
        "majority_baseline_accuracy": float((y == 0).mean()),
        "top_effect_sizes": d.head(6).round(2).to_dict(),
        "weakest_effect_sizes": d.abs().sort_values().head(5).round(2).to_dict(),
        "n_pairs_abs_r_ge_0.95": len(pairs),
    }

    lines = [
        "# EDA summary (generated by `python -m wdbc.eda`)",
        "",
        f"- Samples: {summary['n_samples']}  |  features: {summary['n_features']}",
        f"- Benign: {summary['n_benign']}  |  malignant: {summary['n_malignant']}",
        (
            f"- Always-predict-benign accuracy: {summary['majority_baseline_accuracy']:.1%}"
            " (the bar every model must clear)"
        ),
        "",
        "## Features that best separate the classes (Cohen's d, training split)",
        "",
        "| feature | d |",
        "| --- | --- |",
        *[f"| {k} | {v:.2f} |" for k, v in summary["top_effect_sizes"].items()],
        "",
        "## Weakest features (|d|)",
        "",
        "| feature | abs d |",
        "| --- | --- |",
        *[f"| {k} | {v:.2f} |" for k, v in summary["weakest_effect_sizes"].items()],
        "",
        f"## Nearly duplicate features: {len(pairs)} pairs with |r| >= 0.95",
        "",
        "| feature a | feature b | r |",
        "| --- | --- | --- |",
        *[f"| {a} | {b} | {r:.3f} |" for a, b, r in pairs.itertuples(index=False)],
        "",
        (
            "Radius, perimeter and area are geometrically linked (perimeter ~ 2*pi*r,"
            " area ~ pi*r^2), so they carry almost the same information. Regularisation"
            " (the L2 term) keeps logistic regression stable despite this collinearity."
        ),
        "",
        "![class balance](figures/class_balance.png)",
        "![feature separation](figures/feature_separation.png)",
        "![correlation](figures/correlation_heatmap.png)",
    ]
    reports = cfg["paths"]["reports_dir"]
    (reports / "eda_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return summary


if __name__ == "__main__":
    s = run_eda(load_config())
    print(
        f"EDA done: {s['n_samples']} samples, {s['n_pairs_abs_r_ge_0.95']} highly correlated pairs."
    )
    print("See reports/eda_summary.md and reports/figures/.")
